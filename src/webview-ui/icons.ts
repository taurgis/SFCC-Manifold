/**
 * Get appropriate icon for node type
 */
export function getNodeTypeIcon(type: string): string {
  switch (type) {
    case "start":
      return iconSvgs.play;
    case "end":
      return iconSvgs.stop;
    case "pipelet":
      return iconSvgs.box;
    case "call":
      return iconSvgs.phoneCall;
    case "jump":
      return iconSvgs.arrowRight;
    case "interaction":
      return iconSvgs.user;
    case "decision":
      return iconSvgs.gitBranch;
    case "join":
      return iconSvgs.merge;
    case "loop":
      return iconSvgs.repeat;
    case "text":
      return iconSvgs.text;
    default:
      return iconSvgs.circle;
  }
}
